const j = (opts: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'jsonb', writable: true, nullable: false, ...opts });
const d = (opts: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'date', writable: true, nullable: true, ...opts });

