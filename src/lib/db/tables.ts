/**
 * Table registry: maps content modules to physical tables + column types.
 * Used by the generic data layer to build type-safe, cast-correct SQL.
 */

export type ColType = 'text' | 'int' | 'numeric' | 'bool' | 'date' | 'timestamptz' | 'jsonb';

export interface ColumnSpec {
  type: ColType;
  /** writable from the CMS layer (else DB-managed) */
  writable?: boolean;
  /** store as NULL instead of the type zero-value when empty */
  nullable?: boolean;
}

export interface TableSpec {
  table: string;
  pk: string;
  columns: Record<string, ColumnSpec>;
  /** maintained timestamps (created_at/updated_at) handled automatically */
  timestamps?: boolean;
  idPrefix?: string;
}

const t = (opts: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'text', writable: true, nullable: true, ...opts });
const n = (opts: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'int', writable: true, nullable: true, ...opts });
